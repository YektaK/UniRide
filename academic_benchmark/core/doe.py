import math
import json
import optuna
from typing import Dict, List, Any, Callable

def create_optuna_study(study_name: str) -> optuna.Study:
    """Create or load an optuna study for parameter tuning."""
    optuna.logging.set_verbosity(optuna.logging.WARNING)
    return optuna.create_study(
        study_name=study_name,
        direction="minimize",
        sampler=optuna.samplers.TPESampler(seed=42)
    )

def run_parameter_tuning(
    algo_name: str,
    problem_name: str,
    param_space: Dict[str, Any],
    evaluator: Callable[[Dict[str, Any]], float],
    n_trials: int = 12
) -> Dict[str, Any]:
    """
    Run Optuna-based parameter tuning.
    
    Args:
        algo_name: Algorithm identifier.
        problem_name: Problem identifier.
        param_space: Parameter space generated by build_optuna_space.
        evaluator: A function that takes a parameter dict and returns an average gap/cost.
        n_trials: Number of TPE trials to run.
        
    Returns:
        Best parameters found.
    """
    study = create_optuna_study(f"{algo_name}_{problem_name}")
    
    def objective(trial: optuna.Trial) -> float:
        params = {}
        for k, v in param_space.items():
            if isinstance(v, list) and len(v) > 0:
                if isinstance(v[0], float):
                    params[k] = trial.suggest_float(k, min(v), max(v))
                elif isinstance(v[0], int):
                    params[k] = trial.suggest_int(k, min(v), max(v))
                else:
                    params[k] = trial.suggest_categorical(k, v)
            else:
                params[k] = v
        return evaluator(params)
    
    study.optimize(objective, n_trials=n_trials)
    return study.best_params
